export const tableMap: Record<string, Table> = Object.fromEntries(tables.map((t) => [t.name, t]));
export const domainMap = Object.fromEntries(domains.map((d) => [d.key, d]));

export interface Relation {
  id: string;
  from: string; // table holding FK
  fromColumn: string;
  to: string;
  toColumn: string;
  kind: "many-to-one" | "one-to-one";
  onDelete: string;
  nullable: boolean;
}

export const relations: Relation[] = tables.flatMap((t) =>
  t.columns
    .filter((c) => c.ref)
    .map((c) => ({
      id: `${t.name}.${c.name}->${c.ref!.table}`,
      from: t.name,
      fromColumn: c.name,
      to: c.ref!.table,
      toColumn: c.ref!.column ?? "id",
      kind: c.ref!.kind ?? (c.unique || (c.pk && t.columns.filter((x) => x.pk).length === 1) ? "one-to-one" : "many-to-one"),
      onDelete: c.ref!.onDelete ?? "restrict",
      nullable: !!c.nullable,
    })),
);

export function pkColumns(t: Table) {
  return t.columns.filter((c) => c.pk).map((c) => c.name);
}
